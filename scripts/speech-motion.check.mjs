import assert from 'node:assert/strict';
import { changeVoicePlayback, sampleSpeech, setSpeechMeter } from '../src/audio/speechMotion.ts';

let now=1000, rms=0, reads=0;
Object.defineProperty(performance,'now',{value:()=>now});
setSpeechMeter(()=>{reads++;return rms;});
const tick=()=>sampleSpeech(now+=34);
assert.deepEqual(tick(),{active:false,mouth:0});
changeVoicePlayback('recorded',1);
assert.deepEqual(tick(),{active:true,mouth:0});
rms=1;
for(let i=0;i<6;i++)tick();
assert.equal(sampleSpeech(now).mouth,3);
const readCount=reads;
sampleSpeech(now+1);
assert.equal(reads,readCount,'Multiple guides share one RMS sample');
changeVoicePlayback('recorded',1);
changeVoicePlayback('recorded',-1);
assert(tick().active);
changeVoicePlayback('recorded',-1);
assert(tick().active);
for(let i=0;i<4;i++)tick();
assert.deepEqual(tick(),{active:false,mouth:0});
console.log('PASS RMS, closed mouth in silence, shared samples, overlap and release');
