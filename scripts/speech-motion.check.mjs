import assert from 'node:assert/strict';
import { changeVoicePlayback, getSpeechFrame, setSpeechMeter, subscribeSpeechFrame } from '../src/audio/speechMotion.ts';
const wait = () => new Promise(resolve => setTimeout(resolve, 80));
let level = 0;
setSpeechMeter(() => level);
const unsubscribe = subscribeSpeechFrame(() => {});
assert.deepEqual(getSpeechFrame(), { active: false, mouth: 0 });
changeVoicePlayback('recorded', 1);
assert.deepEqual(getSpeechFrame(), { active: true, mouth: 0 }, 'Silent PCM does not flap the mouth');
level = 1; await wait(); assert.equal(getSpeechFrame().mouth, 3);
level = .33; await wait(); assert.equal(getSpeechFrame().mouth, 1);
changeVoicePlayback('browser', 1);
changeVoicePlayback('recorded', -1); assert(getSpeechFrame().active, 'Another voice still owns playback');
changeVoicePlayback('browser', -1); assert.deepEqual(getSpeechFrame(), { active: false, mouth: 0 });
changeVoicePlayback('browser', 1); globalThis.document = { hidden: true }; await wait();
assert.deepEqual(getSpeechFrame(), { active: false, mouth: 0 }, 'Hidden tab stays still');
document.hidden = false; await wait(); assert(getSpeechFrame().active);
changeVoicePlayback('browser', -1); unsubscribe();
console.log('PASS speech motion: silence, PCM envelope, overlapping playback, stop, hidden tab and cleanup');
